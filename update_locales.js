function setNestedValue(obj, pathStr, value) {
  const parts = pathStr.split('.');
  let current = obj;
  for (let i = 0; i < parts.length - 1; i++) {
    if (!current[parts[i]]) {
      current[parts[i]] = {};
    }
    current = current[parts[i]];
  }
  current[parts[parts.length - 1]] = value;
}

['en', 'fr', 'ar'].forEach(lang => {
  const filePath = path.join(jsonOutputDir, `${lang}.json`);
  if (fs.existsSync(filePath)) {
    const fileContent = fs.readFileSync(filePath, 'utf8');
    const langDict = JSON.parse(fileContent);
    
    // Merge new keys
    const newTranslations = additionalTranslations[lang] || {};
    Object.keys(newTranslations).forEach(nestedPath => {
      setNestedValue(langDict, nestedPath, newTranslations[nestedPath]);
    });

    fs.writeFileSync(filePath, JSON.stringify(langDict, null, 2));
    console.log(`Updated ${lang}.json`);
  }
});
